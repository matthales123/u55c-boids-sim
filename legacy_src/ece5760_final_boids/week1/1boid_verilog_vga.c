// Detect wallstrikes, update velocity and position
void wallsAndEdges(fix15* x, fix15* y, fix15* vx, fix15* vy)
{
  // Reverse direction if we've hit a wall
  if (hitTop(*y)) {
    *vy = *vy + turnfactor ;
  }
  if (hitBottom(*y)) {
    *vy = *vy - turnfactor ;
  } 
  if (hitRight(*x)) {
    *vx = *vx - turnfactor;
  }
  if (hitLeft(*x)) {
    *vx = *vx + turnfactor;
  } 

  // Update position using velocity
  *x = *x + *vx ;
  *y = *y + *vy ;
}


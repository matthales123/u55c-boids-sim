// measure time
struct timeval t1, t2;
double elapsedTime;
struct timespec delay_time ;
	
int main(void)
{
	delay_time.tv_nsec = 10 ;
	delay_time.tv_sec = 0 ;

	// Declare volatile pointers to I/O registers (volatile 	// means that IO load and store instructions will be used 	// to access these pointer locations, 
	// instead of regular memory loads and stores) 
  	
	// === need to mmap: =======================
	// FPGA_CHAR_BASE
	// FPGA_ONCHIP_BASE      
	// HW_REGS_BASE        
  
	// === get FPGA addresses ==================
    // Open /dev/mem
	if( ( fd = open( "/dev/mem", ( O_RDWR | O_SYNC ) ) ) == -1 ) 	{
		printf( "ERROR: could not open \"/dev/mem\"...\n" );
		return( 1 );
	}
    
    // get virtual addr that maps to physical
	// for light weight bus
	h2p_lw_virtual_base = mmap( NULL, HW_REGS_SPAN, ( PROT_READ | PROT_WRITE ), MAP_SHARED, fd, HW_REGS_BASE );	
	if( h2p_lw_virtual_base == MAP_FAILED ) {
		printf( "ERROR: mmap1() failed...\n" );
		close( fd );
		return(1);
	}
	
	// === get VGA char addr =====================
	// get virtual addr that maps to physical
	vga_char_virtual_base = mmap( NULL, FPGA_CHAR_SPAN, ( PROT_READ | PROT_WRITE ), MAP_SHARED, fd, FPGA_CHAR_BASE );	
	if( vga_char_virtual_base == MAP_FAILED ) {
		printf( "ERROR: mmap2() failed...\n" );
		close( fd );
		return(1);
	}
    
    // Get the address that maps to the character 
	vga_char_ptr =(unsigned int *)(vga_char_virtual_base);

	// === get VGA pixel addr ====================
	// get virtual addr that maps to physical
	// SDRAM
	vga_pixel_virtual_base = mmap( NULL, FPGA_ONCHIP_SPAN, ( PROT_READ | PROT_WRITE ), MAP_SHARED, fd, SDRAM_BASE); //SDRAM_BASE	
	
	if( vga_pixel_virtual_base == MAP_FAILED ) {
		printf( "ERROR: mmap3() failed...\n" );
		close( fd );
		return(1);
	}
    // Get the address that maps to the FPGA pixel buffer
	vga_pixel_ptr =(unsigned int *)(vga_pixel_virtual_base);
	
	// === get RAM FPGA parameter addr =========
	sram_virtual_base = mmap( NULL, FPGA_ONCHIP_SPAN, ( PROT_READ | PROT_WRITE ), MAP_SHARED, fd, FPGA_ONCHIP_BASE); //fp	
	
	if( sram_virtual_base == MAP_FAILED ) {
		printf( "ERROR: mmap3() failed...\n" );
		close( fd );
		return(1);
	}
    // Get the address that maps to the RAM buffer
	sram_ptr =(unsigned int *)(sram_virtual_base);
	
	// ===========================================

	/* create a message to be displayed on the VGA 
          and LCD displays */
	char text_top_row[40] = "DE1-SoC ARM/FPGA\0";
	char text_bottom_row[40] = "Cornell ece5760\0";
	char num_string[20], time_string[50] ;
	
	// a pixel from the video
	int pixel_color;
	// video input index
	int i,j, count;
	
	// clear the screen
	VGA_box (0, 0, 639, 479, 0x00);
	// clear the text
	VGA_text_clear();
	VGA_text (1, 56, text_top_row);
	VGA_text (1, 57, text_bottom_row);

	// Spawn a boid
    spawnBoid(&boid0_x, &boid0_y, &boid0_vx, &boid0_vy);

	count = 0;
    while(1) {
        drawArena();
        int x1, y1, x2, y2, color;
        // sram buffer
        // addr=0 start bit
        // addr=1 x1, addr=2 y1
        // addr=3 x2, addr=4 y2
        // addr=5 color
        // query for x1,y1,x2,y2, color(1-byte hex)
        //scanf("%d %d %d %d %d", &x1, &y1, &x2, &y2, &color);
        //printf("data entered\n\r");
        
        x1 = fix2int15(boid0_x);//rand() & 0x7f;
        x2 = fix2int15(boid0_x)+2;//x1 + (rand() & 0x7f);
        y1 = fix2int15(boid0_y);//(rand() & 0xff) ;
        y2 = fix2int15(boid0_y)+2;//y1 + (rand() & 0xff) ;
        color = BLACK;
        // start the timer
        gettimeofday(&t1, NULL);
        // set up parameters
        *(sram_ptr+1) = x1;
        *(sram_ptr+2) = y1;
        *(sram_ptr+3) = x2;
        *(sram_ptr+4) = y2;
        *(sram_ptr+5) = color;
        *(sram_ptr) = 1; // the "data-ready" flag
    
        // wait for FPGA to zero the "data_ready" flag
        while (*(sram_ptr)==1) ;
        
        wallsAndEdges(&boid0_x, &boid0_y, &boid0_vx, &boid0_vy) ;

        x1 = fix2int15(boid0_x);//rand() & 0x7f;
        x2 = fix2int15(boid0_x)+2;//x1 + (rand() & 0x7f);
        y1 = fix2int15(boid0_y);//(rand() & 0xff) ;
        y2 = fix2int15(boid0_y)+2;//y1 + (rand() & 0xff) ;
        color = WHITE;
        // set up parameters
        *(sram_ptr+1) = x1;
        *(sram_ptr+2) = y1;
        *(sram_ptr+3) = x2;
        *(sram_ptr+4) = y2;
        *(sram_ptr+5) = color;
        *(sram_ptr) = 1; // the "data-ready" flag
    
        // wait for FPGA to zero the "data_ready" flag
        while (*(sram_ptr)==1) ;

        // time the FPGA
        gettimeofday(&t2, NULL);
        elapsedTime = (t2.tv_sec - t1.tv_sec) * 1000000.0;      // sec to us
        elapsedTime += (t2.tv_usec - t1.tv_usec) ;   // us to 
        //sprintf(num_string, "# = %d     ", total_count);
        sprintf(time_string, "T=%8.0f uSec  ", elapsedTime);
        //VGA_text (10, 3, num_string);
        VGA_text (10, 4, time_string);
        delay(1); 

    }

} // end main

